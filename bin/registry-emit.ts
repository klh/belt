// bin/registry-emit.ts — GENERATE downstream model config FROM the registry
// (bin/registry.ts is the ONE place an LLM is registered). Config over code:
// nothing below declares a port, model id or alias of its own.
//
//   bun bin/registry-emit.ts litellm   # LiteLLM model_list (the :4100 engine)
//   bun bin/registry-emit.ts direct    # routing-policy `direct:` tiers
//   bun bin/registry-emit.ts buckle    # buckle upstreams.yaml model section
//   bun bin/registry-emit.ts json      # the registry document (= /registry.json)
//   bun bin/registry-emit.ts all --out DIR   # all four into DIR
//   … <kind> --out FILE                # one kind into FILE (default stdout)
//
// Hash-stable: no timestamps, port-sorted rows — the same registry emits
// byte-identical output, so a diff of emitted config is a real change.
// No secrets: local rows carry the literal `local` placeholder key; cloud
// keys are env-ref NAMES only and are not this emitter's business.
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import {
	chatEntries,
	type RegistryDoc,
	type RegistryEntry,
	registryDoc,
	registryEntries,
} from "./registry.ts";

const HEADER =
	"# GENERATED by belt bin/registry-emit.ts from bin/registry.ts — do not edit by hand.";
const DEFAULT_HOST = "127.0.0.1";

// plain YAML scalar when safe, JSON-quoted (valid YAML) otherwise
const q = (v: string): string =>
	/^[A-Za-z0-9_./:@+-]+$/.test(v) ? v : JSON.stringify(v);

const baseUrl = (e: RegistryEntry, host: string): string =>
	`http://${host}:${e.port}${e.protocol === "openai" ? "/v1" : ""}`;

/** LiteLLM model_list rows — chat-class OpenAI entries only (rerank, embed
 *  and classify rows speak other API shapes). */
export function litellmRows(
	entries: RegistryEntry[] = registryEntries(),
	host = DEFAULT_HOST,
): string[] {
	return chatEntries(entries).map((e) =>
		[
			`  - model_name: ${q(e.alias)}`,
			"    litellm_params:",
			`      model: ${q(`openai/${e.model}`)}`,
			`      api_base: ${q(baseUrl(e, host))}`,
			"      api_key: local",
		].join("\n"),
	);
}

/** LiteLLM `model_list:` block (the :4100 engine config model entries). */
export const emitLitellmModelList = (
	entries: RegistryEntry[] = registryEntries(),
	host = DEFAULT_HOST,
): string => `model_list:\n${litellmRows(entries, host).join("\n")}\n`;

/** routing-policy `direct:` tiers — every servable row, keyed by alias, so a
 *  router can address any fleet member directly without a gateway hop. */
export function emitDirectTiers(
	entries: RegistryEntry[] = registryEntries(),
	host = DEFAULT_HOST,
): string {
	const rows = entries.map((e) =>
		[
			`  ${q(e.alias)}:`,
			`    url: ${q(baseUrl(e, host))}`,
			`    model: ${q(e.model)}`,
			`    class: ${e.class}`,
			`    role: ${q(e.role)}`,
			`    protocol: ${q(e.protocol)}`,
			`    context_tokens: ${e.contextTokens}`,
			`    tier: ${e.tier}`,
			`    engine: ${e.engine}`,
			`    external: ${e.external}`,
			`    source: ${q(e.source)}`,
		].join("\n"),
	);
	return `direct:\n${rows.join("\n")}\n`;
}

/** buckle upstreams.yaml `groups:` model section — one group per chat alias
 *  plus the `local-swarm` pool. Merge it over buckle's committed default via
 *  BUCKLE_UPSTREAMS (same-named groups are replaced). */
export function emitBuckleUpstreams(
	entries: RegistryEntry[] = registryEntries(),
	host = DEFAULT_HOST,
): string {
	const chat = chatEntries(entries);
	const dep = (e: RegistryEntry): string =>
		[
			`    - url: ${q(`http://${host}:${e.port}`)}`,
			"      dialect: openai",
			"      adapter: openai-compat",
			`      model: ${q(e.model)}`,
		].join("\n");
	const groups = chat.map((e) => `  ${q(e.alias)}:\n${dep(e)}`);
	groups.push(`  local-swarm:\n${chat.map(dep).join("\n")}`);
	return `version: 1\n\ngroups:\n${groups.join("\n")}\n`;
}

/** Canonical registry JSON — the /registry.json body. */
export const registryJson = (doc: RegistryDoc = registryDoc()): string =>
	`${JSON.stringify(doc, null, "\t")}\n`;

/** Strong ETag over the exact body bytes. */
export function registryEtag(body: string): string {
	const h = new Bun.CryptoHasher("sha256").update(body).digest("hex");
	return `"sha256-${h.slice(0, 32)}"`;
}

/** GET|HEAD /registry.json handler (router shim; hubs proxy it verbatim). */
export function registryResponse(
	req: Request,
	doc: RegistryDoc = registryDoc(),
): Response {
	const body = registryJson(doc);
	const etag = registryEtag(body);
	const headers = {
		"content-type": "application/json; charset=utf-8",
		etag,
		"cache-control": "no-cache",
	};
	const inm = req.headers.get("if-none-match") ?? "";
	if (
		inm
			.split(",")
			.map((t) => t.trim())
			.some((t) => t === etag || t === "*")
	)
		return new Response(null, { status: 304, headers });
	return new Response(req.method === "HEAD" ? null : body, { headers });
}

export const EMITTERS = {
	litellm: (): string => `${HEADER}\n${emitLitellmModelList()}`,
	direct: (): string => `${HEADER}\n${emitDirectTiers()}`,
	buckle: (): string => `${HEADER}\n${emitBuckleUpstreams()}`,
	json: (): string => registryJson(),
} as const;
type Kind = keyof typeof EMITTERS;

const FILES: Record<Kind, string> = {
	litellm: "litellm-models.yaml",
	direct: "routing-direct.yaml",
	buckle: "upstreams.models.yaml",
	json: "registry.json",
};

async function main(argv: string[]): Promise<number> {
	const kind = argv[0] ?? "";
	const outAt = argv.indexOf("--out");
	const out = outAt >= 0 ? argv[outAt + 1] : undefined;
	if (kind === "all") {
		if (!out) {
			console.error("registry-emit: all needs --out DIR");
			return 2;
		}
		mkdirSync(out, { recursive: true });
		for (const k of Object.keys(EMITTERS) as Kind[])
			await Bun.write(join(out, FILES[k]), EMITTERS[k]());
		console.error(
			`registry-emit: wrote ${Object.values(FILES).join(", ")} → ${out}`,
		);
		return 0;
	}
	if (!(kind in EMITTERS)) {
		console.error(
			"usage: bun bin/registry-emit.ts <litellm|direct|buckle|json|all> [--out PATH]",
		);
		return 2;
	}
	const text = EMITTERS[kind as Kind]();
	if (out) await Bun.write(out, text);
	else await Bun.write(Bun.stdout, text);
	return 0;
}

if (import.meta.main) process.exit(await main(process.argv.slice(2)));
